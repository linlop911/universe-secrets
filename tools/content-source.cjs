'use strict';
/* The only place that turns source data into the runtime content script and the storyboard. */
const fs = require('node:fs');
const assert = require('node:assert/strict');
const paths = require('./paths.cjs');

const duration = 44;
const read = name => JSON.parse(fs.readFileSync(paths.data(name), 'utf8'));

function load() {
  const chapters = read('chapter-content.json');
  const voices = read('voiceover.json');
  const manifest = read('asset-manifest.json');
  for (const [id, chapter] of Object.entries(chapters)) {
    assert.equal(voices[id].length, chapter.frames.length, id + ': voice count');
    chapter.frames.forEach((frame, index) => { frame.voice = voices[id][index]; });
    assert.equal(chapter.frames[0].at, 0, id + ': first beat');
    assert.ok(chapter.frames.at(-1).at < duration, id + ': last beat must leave a closing hold');
    const times = chapter.frames.map(frame => frame.at);
    assert.deepEqual(times, [...times].sort((a, b) => a - b), id + ': beat order');
    assert.ok(chapter.sourceUrl.startsWith('https://'), id + ': source');
    for (const assetId of chapter.assets) assert.ok(manifest.assets.some(asset => asset.id === assetId), id + ': asset ' + assetId);
  }
  return { duration, chapters, assets: manifest.assets };
}

function contentScript() {
  return '/* Generated by node tools/build_content.cjs; local classic script for file://. */\n'
    + 'window.CosmicContent=' + JSON.stringify(load(), null, 2) + ';\n';
}

function storyboard() {
  const { duration, chapters } = load();
  let out = '# 六章分镜与最终旁白稿\n\n'
    + '导览长度：每章 ' + duration + ' 秒。节奏为「钩子 → 建立 → 变量 → 揭示 → 对照 → 收束」，幕点不等距：0 / 6 / 14 / 24 / 33 / 39 秒，最后一幕留出收束停顿。\n'
    + '时间轴使用现有主动画时钟；暂停或隐藏时不追赶。中文旁白以文本形式随导览逐幕显示，未合成口播音轨。\n\n';
  for (const [id, chapter] of Object.entries(chapters)) {
    out += `## ${chapter.number} ${chapter.eyebrow}\n\n开场：${chapter.question.replace('\n', '')}\n\n`
      + `核心操作：${chapter.coreLabel}。来源：[${chapter.sourceLabel}](${chapter.sourceUrl})。\n\n`
      + '| 时间 | 节奏作用 | 镜头与操作 | 画面标题 | 逐幕旁白 | 知识字幕 |\n| --- | --- | --- | --- | --- | --- |\n';
    const roles = ['钩子', '建立', '变量', '揭示', '对照', '收束'];
    chapter.frames.forEach((frame, index) => {
      const end = index < chapter.frames.length - 1 ? chapter.frames[index + 1].at : duration;
      const operations = `相机半径${frame.camera[0]}；仰角${frame.camera[1]}；方位${frame.camera[2]}；`
        + Object.entries(frame.controls).map(([key, value]) => key + '=' + value).join('，')
        + (frame.mode !== undefined ? '；模式' + frame.mode : '')
        + (frame.action ? '；连续穿越' : '') + (frame.evidence ? '；本地资料对照' : '');
      out += `| ${frame.at}—${end}秒 | ${roles[index]} | ${operations} | ${frame.title} | ${frame.voice} | ${frame.text} |\n`;
    });
    out += `\n理解重点：${chapter.evidence}\n\n视觉高潮：${chapter.frames[4].title}。本章记忆点：${chapter.question.replace('\n', '')}\n\n`;
  }
  return out;
}

module.exports = { duration, read, load, contentScript, storyboard };
