'use strict';
/* The only place that turns source data into the runtime content script and storyboards. */
const fs = require('node:fs');
const assert = require('node:assert/strict');
const paths = require('./paths.cjs');

const duration = 44;
const LANGS = ['zh', 'en', 'ja'];
const read = name => JSON.parse(fs.readFileSync(paths.data(name), 'utf8'));

function base() {
  return {
    duration,
    chapters: read('chapter-content.json'),
    voices: read('voiceover.json'),
    assets: read('asset-manifest.json').assets
  };
}

function translated(lang) {
  const tr = read('languages/' + lang + '.json');
  const zh = base();
  const chapters = {};
  for (const [id, source] of Object.entries(zh.chapters)) {
    const t = tr.chapters[id];
    assert.ok(t, lang + ': missing chapter ' + id);
    chapters[id] = {
      ...source,
      ...t,
      related: source.related.map((item, index) => ({ ...item, ...(t.related[index] || {}) })),
      frames: source.frames.map((frame, index) => ({ ...frame, ...(t.frames[index] || {}) }))
    };
    if (source.officialSound) chapters[id].officialSound = { ...source.officialSound, ...(t.officialSound || {}) };
  }
  return {
    duration,
    chapters,
    voices: tr.voices,
    assets: zh.assets.map(asset => ({ ...asset, ...(tr.assets[asset.id] || {}) }))
  };
}

function load(lang = 'zh') {
  assert.ok(LANGS.includes(lang), 'Unsupported language: ' + lang);
  const pack = lang === 'zh' ? base() : translated(lang);
  for (const [id, chapter] of Object.entries(pack.chapters)) {
    assert.equal(pack.voices[id].length, chapter.frames.length, id + ': voice count');
    chapter.frames.forEach((frame, index) => {
      frame.voice = pack.voices[id][index];
      assert.ok(frame.title && frame.text && frame.voice, id + ': frame ' + index + ' copy');
    });
    assert.equal(chapter.frames[0].at, 0, id + ': first beat');
    assert.ok(chapter.frames.at(-1).at < duration, id + ': last beat must leave a closing hold');
    const times = chapter.frames.map(frame => frame.at);
    assert.deepEqual(times, [...times].sort((a, b) => a - b), id + ': beat order');
    assert.ok(chapter.question && chapter.intro && chapter.coreLabel && chapter.kind && chapter.sourceLabel && chapter.evidence, id + ': chapter copy');
    assert.ok(chapter.sourceUrl.startsWith('https://'), id + ': source');
    for (const assetId of chapter.assets) assert.ok(pack.assets.some(asset => asset.id === assetId), id + ': asset ' + assetId);
  }
  for (const asset of pack.assets) {
    assert.ok(asset.title && asset.contentType && asset.processing && asset.supportsClaim, asset.id + ': asset copy');
  }
  return { duration, chapters: pack.chapters, assets: pack.assets };
}

function contentScript() {
  const languages = {};
  for (const lang of LANGS) languages[lang] = load(lang);
  const ui = { zh: { text: {}, js: {} }, en: read('i18n/en.json'), ja: read('i18n/ja.json') };
  for (const lang of ['en', 'ja']) assert.ok(Object.keys(ui[lang].text).length > 50, lang + ': UI dictionary too small');
  return '/* Generated by node tools/build_content.cjs; local classic script for file://. */\n'
    + 'window.CosmicContent=' + JSON.stringify({ duration, defaultLang: 'zh', languages, ui }) + ';\n';
}

function storyboard(lang = 'zh') {
  const { chapters } = load(lang);
  const copy = {
    zh: {
      title: '# 六章分镜与最终旁白稿',
      lead: '导览长度：每章 ' + duration + ' 秒。节奏为「钩子 → 建立 → 变量 → 揭示 → 对照 → 收束」，幕点不等距：0 / 6 / 14 / 24 / 33 / 39 秒，最后一幕留出收束停顿。\n中文旁白以文本形式随导览逐幕显示，未合成口播音轨。',
      open: '开场', core: '核心操作', source: '来源', roles: ['钩子', '建立', '变量', '揭示', '对照', '收束'],
      head: '| 时间 | 节奏作用 | 镜头与操作 | 画面标题 | 逐幕旁白 | 知识字幕 |\n| --- | --- | --- | --- | --- | --- |',
      evidence: '理解重点', climax: '视觉高潮', memory: '本章记忆点'
    },
    en: {
      title: '# Six-chapter storyboard and final voice script',
      lead: 'Tour length: ' + duration + ' seconds per chapter. The rhythm is hook → setup → variable → reveal → comparison → close, with uneven beats at 0 / 6 / 14 / 24 / 33 / 39 seconds and a closing hold. The English voice line is shown as text with the tour; no recorded narration track is shipped.',
      open: 'Opening', core: 'Core control', source: 'Source', roles: ['Hook', 'Setup', 'Variable', 'Reveal', 'Comparison', 'Close'],
      head: '| Time | Beat role | Camera and controls | Frame title | Voice line | Knowledge caption |\n| --- | --- | --- | --- | --- | --- |',
      evidence: 'Key idea', climax: 'Visual climax', memory: 'Memory point'
    },
    ja: {
      title: '# 六章の絵コンテと最終ナレーション',
      lead: 'ガイドの長さ：各章 ' + duration + ' 秒。リズムは「フック → 設定 → 変数 → 提示 → 比較 → 収束」。幕は 0 / 6 / 14 / 24 / 33 / 39 秒の不等間隔で、最後に収束の間を置きます。日本語ナレーションはテキストとして表示し、録音音声は同梱していません。',
      open: '導入', core: '主要操作', source: '出典', roles: ['フック', '設定', '変数', '提示', '比較', '収束'],
      head: '| 時間 | 幕の役割 | カメラと操作 | 画面タイトル | ナレーション | 知識字幕 |\n| --- | --- | --- | --- | --- | --- |',
      evidence: '理解の要点', climax: '視覚のクライマックス', memory: '章の記憶点'
    }
  }[lang];
  let out = copy.title + '\n\n' + copy.lead + '\n\n';
  for (const [id, chapter] of Object.entries(chapters)) {
    out += `## ${chapter.number} ${chapter.eyebrow}\n\n${copy.open}：${chapter.question.replace('\n', ' ')}\n\n`
      + `${copy.core}：${chapter.coreLabel}。${copy.source}：[${chapter.sourceLabel}](${chapter.sourceUrl})。\n\n`
      + copy.head + '\n';
    chapter.frames.forEach((frame, index) => {
      const end = index < chapter.frames.length - 1 ? chapter.frames[index + 1].at : duration;
      const operations = `camera ${frame.camera[0]}, ${frame.camera[1]}, ${frame.camera[2]}; `
        + Object.entries(frame.controls).map(([key, value]) => key + '=' + value).join(', ')
        + (frame.mode !== undefined ? '; mode ' + frame.mode : '')
        + (frame.action ? '; continuous traverse' : '') + (frame.evidence ? '; local evidence' : '');
      out += `| ${frame.at}—${end}s | ${copy.roles[index]} | ${operations} | ${frame.title} | ${frame.voice} | ${frame.text} |\n`;
    });
    out += `\n${copy.evidence}：${chapter.evidence}\n\n${copy.climax}：${chapter.frames[4].title}。${copy.memory}：${chapter.question.replace('\n', ' ')}\n\n`;
  }
  return out;
}

module.exports = { duration, LANGS, read, load, contentScript, storyboard };
